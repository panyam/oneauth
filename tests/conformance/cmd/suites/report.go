// PlanRecord and ModuleRecord mirror oidfplan's run record
// (tests/oidf-conformance/oidfplan/record.go), which the OIDF exercise
// writes as JSON. They are copied rather than imported because the two
// test modules don't depend on each other.
type PlanRecord struct {
	Plan    string            `json:"plan"`
	Variant map[string]string `json:"variant,omitempty"`
	PlanID  string            `json:"plan_id,omitempty"`
	Counts  map[string]int    `json:"counts"`
	Against int               `json:"against"`
	Modules []ModuleRecord    `json:"modules"`
}

// ModuleRecord is one module of a PlanRecord.
type ModuleRecord struct {
	Module   string `json:"module"`
	Status   string `json:"status,omitempty"`
	Result   string `json:"result,omitempty"`
	Verdict  string `json:"verdict"`
	Expected string `json:"expected,omitempty"`
	Issue    int    `json:"issue,omitempty"`
	Note     string `json:"note,omitempty"`
}

// readPlanRecord reads the record at path, or returns nil when there is
// none or it doesn't parse.
func readPlanRecord(path string) *PlanRecord {
	raw, err := os.ReadFile(path)
	if err != nil {
		return nil
	}
	var rec PlanRecord
	if json.Unmarshal(raw, &rec) != nil {
		return nil
	}
	return &rec
}

// Report is docs/conformance/report.json: each registered suite's last
// result. `make conformance` merges each run into it and renders
// docs/conformance/REPORT.md from it.
type Report struct {
	Suites []SuiteReport `json:"suites"`
}

// SuiteReport is one suite's last result. RanAt and Commit say when and
// at which commit it ran, so a stale result shows its age. SkipNote is
// set when a later run skipped the suite and this result was kept.
type SuiteReport struct {
	Name     string      `json:"name"`
	Kind     string      `json:"kind"`
	Covers   string      `json:"covers"`
	Source   string      `json:"source,omitempty"`
	Tracking string      `json:"tracking,omitempty"`
	Result   string      `json:"result"`
	Detail   string      `json:"detail,omitempty"`
	RanAt    string      `json:"ran_at,omitempty"`
	Commit   string      `json:"commit,omitempty"`
	SkipNote string      `json:"skip_note,omitempty"`
	Plan     *PlanRecord `json:"plan,omitempty"`
}

// LoadReport reads the report at path. A missing file is an empty report.
func LoadReport(path string) (*Report, error) {
	raw, err := os.ReadFile(path)
	if os.IsNotExist(err) {
		return &Report{}, nil
	}
	if err != nil {
		return nil, err
	}
	var r Report
	if err := json.Unmarshal(raw, &r); err != nil {
		return nil, fmt.Errorf("%s: %w", path, err)
	}
	return &r, nil
}

// SaveReport writes r as indented JSON to path and its render to mdPath.
func SaveReport(r *Report, path, mdPath string) error {
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		return err
	}
	raw, err := json.MarshalIndent(r, "", "  ")
	if err != nil {
		return err
	}
	if err := os.WriteFile(path, append(raw, '\n'), 0o644); err != nil {
		return err
	}
	return os.WriteFile(mdPath, []byte(Render(r)), 0o644)
}

// Merge returns the report after this run: one entry per registered
// suite, in registry order. A suite that ran takes its new result. A
// suite that was skipped keeps its previous real result, with SkipNote
// saying when and why, since a machine without the suite's prerequisites
// says nothing about the suite. A suite with no run at all is ResultNotRun.
// The suite's description fields always come from the registry.
func Merge(prev *Report, reg *Registry, results []Result, now time.Time, commit string) *Report {
	old := map[string]SuiteReport{}
	if prev != nil {
		for _, s := range prev.Suites {
			old[s.Name] = s
		}
	}
	ran := map[string]Result{}
	for _, r := range results {
		ran[r.Suite.Name] = r
	}
	stamp := now.UTC().Format("2006-01-02 15:04 UTC")
	out := &Report{}
	for _, s := range reg.Suites {
		e, had := old[s.Name]
		if !had {
			e = SuiteReport{Result: ResultNotRun}
		}
		if r, ok := ran[s.Name]; ok {
			if r.Result == ResultSkip && had && e.Result != ResultSkip && e.Result != ResultNotRun {
				e.SkipNote = fmt.Sprintf("skipped %s at %s: %s", stamp, commit, r.Detail)
			} else {
				e = SuiteReport{Result: r.Result, Detail: r.Detail, RanAt: stamp, Commit: commit, Plan: r.Plan}
			}
		}
		if s.Kind == KindManual && s.LastRun != nil {
			e = SuiteReport{Result: ResultManual, Detail: manualDetail(s.LastRun), RanAt: s.LastRun.Date, Commit: s.LastRun.Commit}
		}
		e.Name, e.Kind, e.Covers, e.Source, e.Tracking = s.Name, s.Kind, s.Covers, s.Source, s.Tracking
		out.Suites = append(out.Suites, e)
	}
	return out
}

// Render returns REPORT.md for r. The output depends only on r, so the
// stale check can compare the committed file with a fresh render.
func Render(r *Report) string {
	var b strings.Builder
	b.WriteString("# Conformance report\n\n")
	b.WriteString("Generated by `make conformance` from `docs/conformance/report.json`; don't edit it by hand. ")
	b.WriteString("Each suite in `conformance/suites.yaml` shows its last result, and when and at which commit it ran. ")
	b.WriteString("A gating suite's failure fails the run; an info suite is only reported; a manual suite is run by a person, and its row shows that run. ")
	b.WriteString("Expected outcomes live in `tests/conformance/known-gaps.yaml`, and `docs/CONFORMANCE.md` says which OIDF plans apply.\n\n")
	b.WriteString("| Suite | Kind | Result | Summary | Last run |\n|---|---|---|---|---|\n")
	for _, s := range r.Suites {
		last := "never"
		if s.RanAt != "" {
			last = s.RanAt + ", " + s.Commit
		}
		detail := s.Detail
		if s.SkipNote != "" {
			detail = strings.TrimSpace(detail + " (" + s.SkipNote + ")")
		}
		fmt.Fprintf(&b, "| %s | %s | %s | %s | %s |\n", s.Name, s.Kind, s.Result, cell(detail, 0), last)
	}
	for _, s := range r.Suites {
		fmt.Fprintf(&b, "\n## %s\n\n%s", s.Name, cell(s.Covers, 0))
		if s.Source != "" {
			fmt.Fprintf(&b, " Source: `%s`.", s.Source)
		}
		if s.Tracking != "" {
			fmt.Fprintf(&b, " Tracking: %s.", s.Tracking)
		}
		b.WriteString("\n")
		if s.Plan == nil {
			continue
		}
		p := s.Plan
		fmt.Fprintf(&b, "\nPlan `%s`, %d modules: %s; %d against known-gaps.yaml.\n\n", p.Plan, len(ranModules(p)), counts(p.Counts), p.Against)
		b.WriteString("| Module | Result | Known gap | Note |\n|---|---|---|---|\n")
		for _, m := range p.Modules {
			result := m.Result
			if result == "" {
				result = "-"
			}
			if m.Verdict != "" && m.Verdict != "ok" {
				result += " (" + m.Verdict + ")"
			}
			gap := ""
			if m.Expected != "" {
				gap = m.Expected
				if m.Issue != 0 {
					gap += fmt.Sprintf(", issue %d", m.Issue)
				}
			}
			fmt.Fprintf(&b, "| `%s` | %s | %s | %s |\n", m.Module, result, gap, cell(m.Note, 160))
		}
	}
	return b.String()
}

func ranModules(p *PlanRecord) []ModuleRecord {
	var out []ModuleRecord
	for _, m := range p.Modules {
		if m.Result != "" || m.Status != "" {
			out = append(out, m)
		}
	}
	return out
}

func counts(c map[string]int) string {
	keys := make([]string, 0, len(c))
	for k := range c {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	parts := make([]string, 0, len(keys))
	for _, k := range keys {
		parts = append(parts, fmt.Sprintf("%s %d", k, c[k]))
	}
	return strings.Join(parts, ", ")
}

// cell makes s safe for one markdown table cell: newlines become spaces,
// pipes are escaped, and it is cut to max runes when max > 0.
func cell(s string, max int) string {
	s = strings.Join(strings.Fields(s), " ")
	if max > 0 {
		if r := []rune(s); len(r) > max {
			s = string(r[:max]) + "…"
		}
	}
	return strings.ReplaceAll(s, "|", `\|`)
}

// manualDetail is a manual run's summary line: its result, and the doc
// that triages it.
func manualDetail(m *ManualRun) string {
	if m.Doc == "" {
		return m.Result
	}
	return m.Result + " (" + m.Doc + ")"
}
